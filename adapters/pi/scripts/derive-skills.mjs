export function headings(text) {
	return text.split("\n").filter((line) => /^##+ /.test(line)).map((line) => line.trim());
}

function countMatches(pattern, text) {
	const flags = pattern.flags.includes("g") ? pattern.flags : `${pattern.flags}g`;
	return [...text.matchAll(new RegExp(pattern.source, flags))].length;
}

export function deriveSkill(skill, canonical) {
	let text = canonical;
	for (const rule of skill.rules) {
		const matches = countMatches(rule.pattern, text);
		if (rule.required && matches === 0) {
			throw new Error(`${skill.source}: required rule "${rule.name}" matched nothing; update scripts/derive-skills.mjs`);
		}
		text = text.replace(rule.pattern, rule.replace);
	}
	const end = text.indexOf("\n---\n", 4);
	if (!text.startsWith("---\n") || end < 0) throw new Error(`${skill.source}: missing frontmatter`);
	text = `${text.slice(0, end + 5)}\n${GENERATED(skill.source)}\n${text.slice(end + 5)}`;
	for (const forbidden of FORBIDDEN) {
		if (forbidden.pattern.test(text)) throw new Error(`${skill.source}: derived text still contains ${forbidden.name}`);
	}
	const derivedHeadings = new Set(headings(text));
	for (const heading of headings(canonical)) {
		if (!derivedHeadings.has(heading) && !skill.dropHeadings.includes(heading)) {
			throw new Error(`${skill.source}: heading "${heading}" is missing from the derivation and not in dropHeadings`);
		}
	}
	return text;
}

export async function expectedFiles() {
	const files = new Map();
	for (const skill of SKILLS) {
		const canonical = await fs.readFile(join(repoRoot, skill.source), "utf8");
		files.set(join(skill.dir, "SKILL.md"), Buffer.from(deriveSkill(skill, canonical), "utf8"));
		for (const [from, to] of skill.copies) files.set(join(skill.dir, to), await fs.readFile(join(repoRoot, from)));
	}
	return files;
}

async function listFiles(root) {
	if (!existsSync(root)) return [];
	const out = [];
	for (const entry of await fs.readdir(root, { withFileTypes: true, recursive: true })) {
		if (entry.isFile()) out.push(relative(root, join(entry.parentPath ?? entry.path, entry.name)));
	}
	return out;
}

async function main() {
	const check = process.argv.includes("--check");
	const expected = await expectedFiles();
	const present = await listFiles(skillsRoot);
	const differing = [];
	for (const [path, bytes] of expected) {
		let current;
		try {
			current = await fs.readFile(join(skillsRoot, path));
		} catch {
			current = undefined;
		}
		if (!current || !current.equals(bytes)) differing.push(path);
	}
	const extra = present.filter((path) => !expected.has(path));
	if (check) {
		if (differing.length || extra.length) {
			for (const path of differing) console.error(`differs: skills${sep}${path}`);
			for (const path of extra) console.error(`not derived: skills${sep}${path}`);
			console.error("Run `npm run derive-skills` in adapters/pi.");
			process.exit(1);
		}
		console.log(`skills are up to date (${expected.size} files)`);
		return;
	}
	for (const path of extra) await fs.rm(join(skillsRoot, path));
	for (const [path, bytes] of expected) {
		await fs.mkdir(dirname(join(skillsRoot, path)), { recursive: true });
		await fs.writeFile(join(skillsRoot, path), bytes);
	}
	// Remove directories left empty by deleted files.
	for (const entry of (await fs.readdir(skillsRoot, { withFileTypes: true, recursive: true })).reverse()) {
		if (!entry.isDirectory()) continue;
		const path = join(entry.parentPath ?? entry.path, entry.name);
		if (!(await fs.readdir(path)).length) await fs.rmdir(path);
	}
	console.log(`wrote ${expected.size} files, removed ${extra.length}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main().catch((error) => {
		console.error(error instanceof Error ? error.message : String(error));
		process.exit(1);
	});
}
