//
//   node scripts/derive-skills.mjs          write adapters/pi/skills/
//   node scripts/derive-skills.mjs --check  exit 1 if the committed copies differ
//
// The canonical sources are skills/mmx/SKILL.md (+ references/diff-schema.md)
// and adapters/codemap/SKILL.md (+ its scripts and worked example). The pi
